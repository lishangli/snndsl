"""PyTorch backend: lower the SNN IR to a self-contained ``nn.Module`` source file.

The backend emits *readable Python*, not a pickled object, so the compile step is
auditable: you can diff the generated network, then import it like hand-written
code. Time-step execution is emitted either unrolled (small T) or looped (large
T) based on the ``schedule`` pass.
"""
from __future__ import annotations

import re
from typing import Any, Dict, List, Optional, Tuple

from ..ir import IRGraph, IRNode

HEADER = '''# -*- coding: utf-8 -*-
# ---------------------------------------------------------------------------
# Generated by snndsl from {filename}
# program: {name}    time steps: {steps}    dt: {dt}    schedule: {strategy}
# DO NOT EDIT - recompile from the .snn source instead.
# ---------------------------------------------------------------------------
from __future__ import annotations

import torch
import torch.nn as nn
import torch.nn.functional as F

from snndsl.backends.runtime import (
    rate_current, poisson_encode, latency_encode, rate_readout,
    surrogate_fast_sigmoid, surrogate_sigmoid, surrogate_atan, surrogate_triangle,
    surrogate_super_spike, surrogate_rectangular, surrogate_straight_through,
)
'''


def _safe(name: str) -> str:
    return re.sub(r"[^0-9a-zA-Z_]", "_", name)


_INIT_MAP = {
    "kaiming_normal": "kaiming_normal_", "kaiming_uniform": "kaiming_uniform_",
    "xavier_normal": "xavier_normal_", "xavier_uniform": "xavier_uniform_",
    "orthogonal": "orthogonal_", "normal": "normal_", "uniform": "uniform_",
    "zeros": "zeros_", "ones": "ones_",
}


def _init_fn(name: str) -> str:
    key = str(name).strip().lower()
    return _INIT_MAP.get(key, "kaiming_normal_")


class TorchCodeGen:
    def __init__(self, graph: IRGraph, class_name: str = "SnnNet"):
        self.g = graph
        self.cls = class_name
        self.prod = graph.producers()
        self.lines: List[str] = []
        self.is_spike: Dict[str, bool] = {}
        self.params: List[Tuple[str, str]] = []   # (attr name, node id)
        self.readout = str(graph.infer.get("readout", "spikes")).lower()

    # ------------------------------------------------------------------ util
    def emit(self, indent: int, text: str) -> None:
        self.lines.append("    " * indent + text if text else "")

    def var(self, nid: str) -> str:
        return "v_" + _safe(nid)

    # ------------------------------------------------------------------ main
    def generate(self) -> str:
        g = self.g
        steps = g.temporal.steps
        out = [HEADER.format(filename=g.filename, name=g.name, steps=steps,
                             dt=g.temporal.dt, strategy=g.temporal.strategy)]
        in_shape = tuple(g.node(g.inputs[0]).shape) if g.inputs else ()
        out_node = g.node(g.outputs[0]) if g.outputs else None
        out_shape = tuple(out_node.shape) if out_node else ()

        out.append(f"\nclass {self.cls}(nn.Module):")
        out.append(f'    """Compiled spiking network: {g.name}."""')
        out.append(f"    T = {steps}")
        out.append(f"    DT = {float(g.temporal.dt)}")
        out.append(f'    STRATEGY = "{g.temporal.strategy}"')
        out.append(f"    INPUT_SHAPE = {in_shape!r}")
        out.append(f"    OUTPUT_SHAPE = {out_shape!r}")
        out.append(f'    PROGRAM = "{g.name}"')
        out.append("    NEURON_MODELS = {")
        for nm, spec in g.neurons.items():
            out.append(f'        "{nm}": {{"params": {spec.params!r}, '
                       f'"states": {spec.states!r}, "surrogate": "{spec.surrogate}"}},')
        out.append("    }")
        out.append("")

        self.lines = out
        self._gen_init()
        self._gen_reset()
        self._gen_penalty()
        self._gen_forward()
        return "\n".join(self.lines) + "\n"

    # ---------------------------------------------------------------- __init__
    def _gen_init(self) -> None:
        g = self.g
        self.emit(1, "def __init__(self):")
        self.emit(2, "super().__init__()")
        self.emit(2, "self.spike_trace = {}")
        self.emit(2, "self.collect = False")
        self.emit(2, "self.track_pen = False")
        self.emit(2, "self._pen_acc = None")
        n_param_layers = 0
        for n in g.nodes:
            if n.op == "dense":
                w = f"w_{_safe(n.id)}"
                units = n.attrs["units"]
                inf = n.attrs["in_features"]
                self.emit(0, "")
                self.emit(2, f"# dense {n.name}: {inf} -> {units}")
                self.emit(2, f"self.{w} = nn.Parameter(torch.empty({units}, {inf}))")
                if n.attrs.get("bias", True):
                    self.emit(2, f"self.b_{_safe(n.id)} = nn.Parameter(torch.zeros({units}))")
                n_param_layers += 1
            elif n.op == "conv":
                cout = n.attrs["out_channels"]
                cin = n.attrs["in_channels"]
                k = n.attrs["kernel"]
                grp = n.attrs.get("groups", 1)
                self.emit(0, "")
                self.emit(2, f"# conv {n.name}: {cin} -> {cout} k={k} s={n.attrs['stride']} "
                             f"p={n.attrs['padding']}")
                self.emit(2, f"self.w_{_safe(n.id)} = nn.Parameter("
                             f"torch.empty({cout}, {cin // grp}, {k}, {k}))")
                if n.attrs.get("bias", True):
                    self.emit(2, f"self.b_{_safe(n.id)} = nn.Parameter(torch.zeros({cout}))")
                n_param_layers += 1
        self.emit(0, "")
        self.emit(2, "self._init_weights()")
        self.emit(0, "")
        for n in g.nodes:
            if n.op in ("dense", "conv"):
                self.params.append((f"w_{_safe(n.id)}", n.id))

    def _gen_reset(self) -> None:
        self.emit(0, "")
        self.emit(1, "def _init_weights(self):")
        any_init = False
        for n in self.g.nodes:
            if n.op == "dense":
                init = _init_fn(n.attrs.get("init", "kaiming_normal"))
                scale = float(n.attrs.get("weight_scale", 1.0))
                self.emit(2, f"nn.init.{init}(self.w_{_safe(n.id)}, nonlinearity='linear')")
                if scale != 1.0:
                    self.emit(2, f"self.w_{_safe(n.id)}.data.mul_({scale})")
                any_init = True
            elif n.op == "conv":
                init = _init_fn(n.attrs.get("init", "kaiming_normal"))
                self.emit(2, f"nn.init.{init}(self.w_{_safe(n.id)}, nonlinearity='relu')")
                any_init = True
        if not any_init:
            self.emit(2, "pass")

        self.emit(0, "")
        self.emit(1, "def _reset_state(self, batch, device, dtype):")
        neuron_nodes = [n for n in self.g.nodes if n.op == "neuron"]
        if not neuron_nodes:
            self.emit(2, "return {}")
            return
        self.emit(2, "st = {}")
        for n in neuron_nodes:
            spec = self.g.neurons[n.attrs["model"]]
            self.emit(2, f'st["{n.id}"] = {{')
            for sname, sval in spec.states.items():
                self.emit(3, f'"{sname}": torch.full((batch,) + {tuple(n.shape)!r}, '
                             f'{float(sval)!r}, device=device, dtype=dtype),')
            self.emit(2, "}")
        self.emit(2, "return st")

    def _state_shape(self, n: IRNode) -> Tuple[int, ...]:
        return tuple(n.shape)

    def _gen_penalty(self) -> None:
        self.emit(0, "")
        self.emit(1, "def spike_penalty(self):")
        self.emit(2, "return self._pen_acc if self._pen_acc is not None "
                     "else torch.zeros((), device=next(self.parameters()).device)")

    # ---------------------------------------------------------------- forward
    def _gen_forward(self) -> None:
        g = self.g
        self.emit(0, "")
        self.emit(1, "def forward(self, x):")
        self.emit(2, "batch = x.shape[0]")
        self.emit(2, "st = self._reset_state(batch, x.device, x.dtype)")
        if g.train.get("reg") and isinstance(g.train["reg"], dict) and \
                g.train["reg"].get("fn") == "spike_l2":
            self.emit(2, "self._pen_acc = None")
        self.emit(2, "if self.collect:")
        self.emit(3, "self.spike_trace = {}")
        accs = [n for n in g.nodes if n.op == "output"]
        for n in accs:
            self.emit(2, f"acc_{_safe(n.id)} = None")
        self.emit(0, "")

        if g.temporal.strategy == "unrolled":
            for k in range(g.temporal.steps):
                self.emit(2, f"# ---- time step {k} ----")
                self._emit_body(2, t_expr=str(k))
        else:
            self.emit(2, "for t in range(self.T):")
            self._emit_body(3, t_expr="t")

        self.emit(0, "")
        if len(accs) == 1:
            n = accs[0]
            self.emit(2, f"return rate_readout(acc_{_safe(n.id)}, self.T)")
        else:
            self.emit(2, "return {")
            for n in accs:
                self.emit(3, f'"{n.name}": rate_readout(acc_{_safe(n.id)}, self.T),')
            self.emit(2, "}")

    def _emit_body(self, ind: int, t_expr: str) -> None:
        g = self.g
        for n in g.nodes:
            self._emit_node(n, ind, t_expr)

    # ------------------------------------------------------------------ nodes
    def _emit_node(self, n: IRNode, ind: int, t_expr: str) -> None:
        op = n.op
        if op == "output":
            src = self.var(n.inputs[0])
            if self.readout == "membrane":
                producer = self.prod.get(n.inputs[0])
                if producer is not None and producer.op == "neuron":
                    src = f"{self.var(producer.id)}_mem"
            acc = f"acc_{_safe(n.id)}"
            self.emit(ind, f"# output {n.name} <- {self.prod[n.inputs[0]].name}"
                           f"  (readout={self.readout})")
            self.emit(ind, f"{acc} = {src} if {acc} is None else {acc} + {src}")
            return
        getattr(self, f"_op_{op}")(n, ind, t_expr)

    def _op_input(self, n: IRNode, ind: int, t_expr: str) -> None:
        self.emit(ind, f"# input {n.name} shape={list(n.shape)}")
        self.emit(ind, f"{self.var(n.id)} = x")

    def _op_encode(self, n: IRNode, ind: int, t_expr: str) -> None:
        src = self.var(n.inputs[0])
        scheme = n.attrs.get("scheme", "rate")
        gain = float(n.attrs.get("gain", 1.0))
        if scheme in ("rate", "current", "direct"):
            call = f"rate_current({src}, {gain})"
        elif scheme in ("poisson", "bernoulli"):
            call = f"poisson_encode({src}, {gain})"
        elif scheme in ("latency", "ttfs"):
            call = f"latency_encode({src}, {t_expr}, {gain}, self.T)"
        else:
            call = f"rate_current({src}, {gain})"
        self.emit(ind, f"# encode {n.name} scheme={scheme}")
        self.emit(ind, f"{self.var(n.id)} = {call}")
        self.is_spike[n.id] = scheme in ("poisson", "bernoulli", "latency", "ttfs")

    def _op_dense(self, n: IRNode, ind: int, t_expr: str) -> None:
        src = self.var(n.inputs[0])
        w = f"self.w_{_safe(n.id)}"
        b = f"self.b_{_safe(n.id)}" if n.attrs.get("bias", True) else "None"
        self.emit(ind, f"# dense {n.name} {n.attrs['in_features']}->{n.attrs['units']}")
        self.emit(ind, f"{self.var(n.id)} = F.linear({src}.reshape(batch, -1), {w}, {b})")

    def _op_conv(self, n: IRNode, ind: int, t_expr: str) -> None:
        src = self.var(n.inputs[0])
        w = f"self.w_{_safe(n.id)}"
        b = f"self.b_{_safe(n.id)}" if n.attrs.get("bias", True) else "None"
        self.emit(ind, f"# conv {n.name} k={n.attrs['kernel']} s={n.attrs['stride']} "
                       f"p={n.attrs['padding']}")
        self.emit(ind, f"{self.var(n.id)} = F.conv2d({src}, {w}, {b}, "
                       f"stride={n.attrs['stride']}, padding={n.attrs['padding']}, "
                       f"groups={n.attrs.get('groups', 1)})")

    def _op_pool(self, n: IRNode, ind: int, t_expr: str) -> None:
        src = self.var(n.inputs[0])
        k = n.attrs["kernel"]
        s = n.attrs["stride"]
        fn = "F.avg_pool2d" if n.attrs.get("kind", "avg") == "avg" else "F.max_pool2d"
        self.emit(ind, f"# pool {n.name} {n.attrs.get('kind', 'avg')} k={k}")
        self.emit(ind, f"{self.var(n.id)} = {fn}({src}, {k}, {s})")

    def _op_flatten(self, n: IRNode, ind: int, t_expr: str) -> None:
        self.emit(ind, f"# flatten {n.name}")
        self.emit(ind, f"{self.var(n.id)} = {self.var(n.inputs[0])}.reshape(batch, -1)")

    def _op_dropout(self, n: IRNode, ind: int, t_expr: str) -> None:
        self.emit(ind, f"# dropout {n.name} p={n.attrs.get('p')} (training only)")
        self.emit(ind, f"{self.var(n.id)} = F.dropout({self.var(n.inputs[0])}, "
                       f"{n.attrs.get('p')}, self.training)")

    def _op_add(self, n: IRNode, ind: int, t_expr: str) -> None:
        parts = " + ".join(self.var(i) for i in n.inputs)
        self.emit(ind, f"# add {n.name}")
        self.emit(ind, f"{self.var(n.id)} = {parts}")

    def _op_concat(self, n: IRNode, ind: int, t_expr: str) -> None:
        axis = n.attrs.get("axis", 0) + 1   # +1 for batch dim
        parts = ", ".join(self.var(i) for i in n.inputs)
        self.emit(ind, f"# concat {n.name} axis={n.attrs.get('axis', 0)}")
        self.emit(ind, f"{self.var(n.id)} = torch.cat([{parts}], dim={axis})")

    def _op_neuron(self, n: IRNode, ind: int, t_expr: str) -> None:
        g = self.g
        spec = g.neurons[n.attrs["model"]]
        src = self.var(n.inputs[0])
        direct = n.attrs.get("direct_input", False)
        out = self.var(n.id)
        membrane = self.readout == "membrane"
        self.emit(ind, f"# neuron {n.name} model={spec.name}"
                       + (" [direct input]" if direct else ""))
        self.emit(ind, f"_st = st[\"{n.id}\"]")
        # constants first so the body reads like the DSL source
        self.emit(ind, f"dt = self.DT")
        self.emit(ind, f"t = {t_expr}")
        for p, v in spec.params.items():
            self.emit(ind, f"{p} = {float(v)!r}")
        self.emit(ind, f"i = {src}")
        for s in spec.states:
            self.emit(ind, f"{s} = _st[\"{s}\"]")
        captured = False
        for kind, target, srcln in spec.body:
            # membrane readout keeps the potential *before* the reset, which is
            # where the evidence for the winning class actually lives
            if membrane and not captured and kind == "spike":
                self.emit(ind, f"{out}_mem = {next(iter(spec.states))}")
                captured = True
            self.emit(ind, f"{target} = {srcln}")
        if membrane and not captured:
            self.emit(ind, f"{out}_mem = {next(iter(spec.states))}")
        for s in spec.states:
            self.emit(ind, f"_st[\"{s}\"] = {s}")
        self.emit(ind, out + " = " + spec.spike_var)
        self.is_spike[n.id] = True
        if self._needs_collect():
            self.emit(ind, "if self.collect:")
            self.emit(ind + 1, f'self.spike_trace["{n.id}"] = '
                               f'self.spike_trace.get("{n.id}", 0.0) + '
                               f'{spec.spike_var}.detach().mean().item()')
        if self._needs_penalty():
            self.emit(ind, "if self.track_pen:")
            self.emit(ind + 1, f"self._pen_acc = {spec.spike_var}.mean() if "
                               f"self._pen_acc is None else self._pen_acc + "
                               f"{spec.spike_var}.mean()")

    def _needs_collect(self) -> bool:
        return True

    def _needs_penalty(self) -> bool:
        reg = self.g.train.get("reg")
        return isinstance(reg, dict) and reg.get("fn") == "spike_l2"


def generate_module(graph: IRGraph, class_name: str = "SnnNet") -> str:
    return TorchCodeGen(graph, class_name).generate()


def write_module(graph: IRGraph, path: str, class_name: str = "SnnNet") -> str:
    src = generate_module(graph, class_name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(src)
    return src
